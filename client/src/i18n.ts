function readSavedLanguage(): Language {
  try {
    const stored = localStorage.getItem("startup-game-language");
    return stored === "en" ? "en" : "ru";
  } catch {
    return "ru";
  }
}

export function getLanguage(): Language {
  return i18next.resolvedLanguage === "en" ? "en" : "ru";
}

export function setLanguage(next: Language): void {
  if (getLanguage() === next) return;
  try { localStorage.setItem("startup-game-language", next); } catch { /* Private mode may disable storage. */ }
  void i18next.changeLanguage(next);
}

i18next.use(initReactI18next).init({
  resources: { ru: { translation: russian }, en: { translation: english } },
  lng: readSavedLanguage(),
  fallbackLng: "ru",
  interpolation: { escapeValue: false },
  initAsync: false,
});

export function translate(key: MessageKey, options?: Record<string, string | number>): string {
  return i18next.t(key, options);
}

export function useI18n() {
  const { i18n, t: translateInComponent } = useTranslation();
  const t = useCallback((key: MessageKey, options?: Record<string, string | number>) => translateInComponent(key, options), [translateInComponent]);
  return {
    language: i18n.resolvedLanguage === "en" ? "en" as const : "ru" as const,
    setLanguage,
    t,
  };
}

export type { MessageKey };
